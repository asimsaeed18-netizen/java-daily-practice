
package com.example.week_1.day_3;

public class Exercise10 {
    public static void main(String[] args) {

        // ArrayList:
        // Use ArrayList when you want to store items in a list
        // and access them quickly using their index.
        // Example: Storing a list of student names.

        // LinkedList:
        // Use LinkedList when you need to add or remove
        // elements frequently, especially at the beginning
        // or end of the list.
        // Example: Managing a queue of tasks.

        // HashMap:
        // Use HashMap when you want to store data as
        // key-value pairs and search using a key.
        // It does not guarantee the order of elements.
        // Example: Storing student IDs and their names.

        // TreeMap:
        // Use TreeMap when you want to store key-value pairs
        // with keys automatically sorted in ascending order.
        // Example: Storing student IDs in sorted order.

        System.out.println("ArrayList: Fast index-based access.");
        System.out.println("LinkedList: Useful for frequent insertions and removals.");
        System.out.println("HashMap: Stores key-value pairs without guaranteed order.");
        System.out.println("TreeMap: Stores key-value pairs sorted by keys.");
    }
}